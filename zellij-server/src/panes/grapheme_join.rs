pub const MAX_GROUP_CELLS: usize = 32;
pub const MAX_GROUP_COLUMNS: usize = 255;

pub fn group_end<F>(
    cells: &[crate::panes::terminal_character::TerminalCharacter],
    start: usize,
    mut same_style: F,
) -> usize
where
    F: FnMut(usize, usize) -> bool,
{
    let mut end = start + 1;
    if end >= cells.len() {
        return end.min(cells.len());
    }
    if !may_join(cells[start].last_char(), cells[end].character) {
        return end;
    }
    let mut text = String::new();
    cells[start].push_text_to(&mut text);
    let mut columns = cells[start].width();
    while end < cells.len() && end - start < MAX_GROUP_CELLS {
        let previous = &cells[end - 1];
        let next = &cells[end];
        if !may_join(previous.last_char(), next.character) {
            break;
        }
        if columns + next.width() > MAX_GROUP_COLUMNS {
            break;
        }
        let offset = text.len();
        next.push_text_to(&mut text);
        if is_boundary_at(&text, offset) {
            break;
        }
        if !same_style(end - 1, end) {
            break;
        }
        columns += next.width();
        end += 1;
    }
    end
}

pub struct UnitText {
    pub text: String,
    pub strip_vs16: bool,
    pub complex: bool,
}

pub fn prepare_unit(
    cells: &[crate::panes::terminal_character::TerminalCharacter],
    columns: usize,
) -> UnitText {
    let mut text = String::new();
    for cell in cells {
        cell.push_text_to(&mut text);
    }
    let mut draw_width = unicode_width::UnicodeWidthStr::width(text.as_str());
    let mut strip_vs16 = false;
    if columns < draw_width && text.contains('\u{FE0F}') {
        text.retain(|c| c != '\u{FE0F}');
        draw_width = unicode_width::UnicodeWidthStr::width(text.as_str());
        strip_vs16 = true;
    }
    let complex = if cells.len() > 1 {
        true
    } else {
        let summed: usize = text.chars().map(|c| c.width().unwrap_or(0)).sum();
        !(summed == draw_width && draw_width == columns)
    };
    if text.is_empty() {
        text.push(' ');
    }
    UnitText {
        text,
        strip_vs16,
        complex,
    }
}

pub fn unit_column_spans(
    cells: &[crate::panes::terminal_character::TerminalCharacter],
    may_have_groups: bool,
) -> Vec<(usize, usize)> {
    let mut spans = Vec::with_capacity(cells.len());
    let mut index = 0;
    let mut column = 0;
    while index < cells.len() {
        let end = if may_have_groups {
            group_end(cells, index, |_, _| true)
        } else {
            index + 1
        };
        let width: usize = cells[index..end].iter().map(|c| c.width()).sum();
        spans.push((column, column + width));
        column += width;
        index = end;
    }
    spans
}
